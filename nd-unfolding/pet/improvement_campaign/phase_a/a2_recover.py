def sha256(path: Path | str, chunk: int = 1 << 24) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as handle:
        while block := handle.read(chunk):
            h.update(block)
    return h.hexdigest()


def arr_sha(a: np.ndarray) -> str:
    return hashlib.sha256(np.ascontiguousarray(a).tobytes()).hexdigest()


def jsonable(o: Any) -> Any:
    if isinstance(o, dict):
        return {str(k): jsonable(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [jsonable(v) for v in o]
    if isinstance(o, np.ndarray):
        return jsonable(o.tolist())
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, float) and not math.isfinite(o):
        return repr(o)
    return o


def write(outdir: Path, name: str, payload: dict[str, Any]) -> None:
    path = outdir / name
    path.write_text(json.dumps(jsonable(payload), indent=1, sort_keys=False) + "\n")
    print(f"[a2] wrote {path}", flush=True)


def verdict(result: str, claim: str, evidence: dict[str, Any]) -> dict[str, Any]:
    assert result in ("PASS", "FAIL", "NOT-TESTABLE", "OBSERVATION")
    return {"result": result, "claim": claim, "evidence": evidence}


def flatten(obj: Any, prefix: str = "") -> dict[str, Any]:
    flat: dict[str, Any] = {}
    if isinstance(obj, dict):
        for k, v in obj.items():
            flat.update(flatten(v, f"{prefix}/{k}" if prefix else str(k)))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            flat.update(flatten(v, f"{prefix}[{i}]"))
    else:
        flat[prefix] = obj
    return flat


def classify(a: Any, b: Any) -> str:
    if isinstance(a, bool) or isinstance(b, bool) or a is None or b is None:
        return "bit_identical" if a == b else "mismatch"
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        if a == b:
            return "bit_identical"
        return ("within_1e-10" if abs(float(a) - float(b)) <= TOL * max(1.0, abs(float(a)))
                else "mismatch")
    return "bit_identical" if a == b else "mismatch"



def compare_reports(committed: dict, recomputed: dict) -> dict[str, Any]:
    fa, fb = flatten(committed), flatten(recomputed)
    keys = sorted(set(fa) | set(fb))
    counts = {"bit_identical": 0, "within_1e-10": 0, "mismatch": 0, "missing": 0}
    mismatches = []
    for k in keys:
        if k not in fa or k not in fb:
            counts["missing"] += 1
            mismatches.append({"leaf": k, "committed": fa.get(k, "<absent>"),
                               "recomputed": fb.get(k, "<absent>")})
            continue
        c = classify(fa[k], fb[k])
        counts[c] += 1
        if c == "mismatch":
            mismatches.append({"leaf": k, "committed": fa[k], "recomputed": fb[k]})
    headline = {}
    for leaf in HEADLINE_LEAVES:
        headline[leaf] = {"committed": fa.get(leaf), "recomputed": fb.get(leaf),
                          "class": classify(fa.get(leaf), fb.get(leaf))}
    pairs = {k.split("/")[-1]: {"committed": fa[k], "recomputed": fb.get(k),
                                "class": classify(fa[k], fb.get(k))}
             for k in fa if k.startswith("paired_differences/")}
    return {"leaves": len(keys), "counts": counts, "mismatches": mismatches[:200],
            "headline": headline, "paired_differences": pairs}


# --------------------------------------------------------------------------- #
# Part 1b: an independent minimal scorer, as a cross-check
# --------------------------------------------------------------------------- #
def independent_recovery(eav_a, w_a, tilt_a, eav_b, w_b, push, edges):
    """The seven-bin score written from the specification, not imported.

    prior = w_truth over half-B truth-passing rows; unfolded = w_truth * push on the same rows;
    target = w_truth * tilt over half-A truth-passing rows; each normalised; R = 1 - |t-u|/|t-p|.
    """
    edges = np.asarray(edges, float)
    p, _ = np.histogram(eav_b, bins=edges, weights=w_b)
    u, _ = np.histogram(eav_b, bins=edges, weights=w_b * push)
    t, _ = np.histogram(eav_a, bins=edges, weights=w_a * tilt_a)
    p, u, t = p / p.sum(), u / u.sum(), t / t.sum()
    return float(1.0 - np.abs(t - u).sum() / np.abs(t - p).sum()), p, u, t



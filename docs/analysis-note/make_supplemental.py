#!/usr/bin/env python3
"""Write, or check, the paper's machine-readable Supplemental Material: the sixteen-cell cross section, its reported
covariance and the cell definitions (DECISION-20261029-joseph-oi160-reproduction-and-q8.md item 2).

usage: make_supplemental.py [--check | --self-test]     (run from anywhere inside the repository)

The three files are generated only from the pinned data product (make_values_fived16.READOUTS["dp"], fd_data_product.json),
never from its CSV side files:
  supplemental/xsec16_cells.csv          the 16 cells R00-R15: the lower and upper edge of each cell on each axis
  supplemental/xsec16_cross_section.csv  each cell's cross section, its uncertainty and its relative uncertainty
  supplemental/xsec16_covariance.csv     the reported covariance C_total + C_resp, 16 x 16
--check exits 0 only if:
  1. each file's sha256 equals its pin in SUPP_PINS;
  2. regenerating from the pinned data product reproduces each file byte for byte;
  3. the files reproduce what the paper prints, to the printed precision: each cell's box (values_fived16.tex box-*),
     its cross section (f-*, three significant figures in 10^-40 cm^2/nucleon), its relative uncertainty under the
     reported covariance (sig-C_total_resp-*, in percent) and the correlation matrix (corr-*, two decimals).
--self-test plants a changed number in a written file, a changed edge and a changed covariance entry, and requires
--check to refuse each."""
import csv
import hashlib
import io
import math
import re
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import make_values_fived16 as mv  # noqa: E402

OUT = HERE / "supplemental"
NAMES = ("xsec16_cells.csv", "xsec16_cross_section.csv", "xsec16_covariance.csv")
SUPP_PINS = {"xsec16_cells.csv": "7b0fb5fdd6453725", "xsec16_cross_section.csv": "8d28a06aa00d3084",
             "xsec16_covariance.csv": "c3fcfb11f0aa3dbd"}     # name -> sha256 prefix, as first written and reviewed
AXES = (("pt", "p_T", "GeV/c"), ("pz", "p_parallel", "GeV/c"), ("eavail", "E_avail", "GeV"), ("q3", "q_3", "GeV/c"),
        ("W", "W", "GeV"))


def header(dp_sha, what):
    return [f"# MINERvA-OmniFold, the sixteen-cell nu_mu CC-inclusive cross section on hydrocarbon in five observables: {what}",
            f"# Generated by docs/analysis-note/make_supplemental.py from fd_data_product.json (sha256 {dp_sha}).",
            "# Cells R00-R15 as in the paper's table of the sixteen-cell cross section. Interval coverage has not been",
            "# validated; the limitations are listed in the paper's Limitations subsection."]


def build(d):
    dp = d["dp"]
    dp_sha = hashlib.sha256((mv.ROOT / mv.READOUTS["dp"][0]).read_bytes()).hexdigest()
    cells = [c["cell"] for c in dp["cells"]]
    assert cells == mv.CELLS and dp["correlation_of"] == "C_total_plus_C_resp"
    C = dp["matrices"]["C_total_plus_C_resp"]
    f = dp["f"]
    n = len(cells)
    assert len(C) == n and all(len(r) == n for r in C) and all(abs(C[i][j] - C[j][i]) <= 1e-12 * abs(C[i][i]) for i in range(n) for j in range(n))
    out = {}
    # the cell definitions
    s = io.StringIO()
    s.write("\n".join(header(dp_sha, "cell definitions") + [
        "# Edges: p_T, p_parallel and q_3 in GeV/c; E_avail and W in GeV. The largest edges (4.5 for p_T, 60 for p_parallel,",
        "# 100 for E_avail, q_3 and W) are the analysis grid's outer edges."]) + "\n")
    w = csv.writer(s, lineterminator="\n")
    w.writerow(["cell"] + [f"{a}_{lh}_{u.replace('/', 'per')}" for a, _, u in AXES for lh in ("low", "high")])
    for c in dp["cells"]:
        w.writerow([c["cell"]] + [f"{c['box'][a][k]:g}" for a, _, _ in AXES for k in (0, 1)])
    out["xsec16_cells.csv"] = s.getvalue()
    # the cross section
    s = io.StringIO()
    s.write("\n".join(header(dp_sha, "cross section") + [
        "# xsec: the cell-integrated cross section in cm^2/nucleon; sigma: the square root of the reported covariance's",
        "# diagonal (C_total + C_resp), in cm^2/nucleon; relative_sigma = sigma / xsec."]) + "\n")
    w = csv.writer(s, lineterminator="\n")
    w.writerow(["cell", "xsec_cm2_per_nucleon", "sigma_cm2_per_nucleon", "relative_sigma"])
    for i, c in enumerate(cells):
        sg = math.sqrt(C[i][i])
        w.writerow([c, f"{f[i]:.9e}", f"{sg:.9e}", f"{sg / f[i]:.9e}"])
    out["xsec16_cross_section.csv"] = s.getvalue()
    # the covariance
    s = io.StringIO()
    s.write("\n".join(header(dp_sha, "reported covariance") + [
        "# The reported covariance C_total + C_resp of the cell-integrated cross sections, in (cm^2/nucleon)^2; rows and",
        "# columns in the cell order R00-R15."]) + "\n")
    w = csv.writer(s, lineterminator="\n")
    w.writerow(["cell"] + cells)
    for i, c in enumerate(cells):
        w.writerow([c] + [f"{C[i][j]:.9e}" for j in range(n)])
    out["xsec16_covariance.csv"] = s.getvalue()
    return out


def read_rows(text):
    return list(csv.reader([l for l in text.splitlines() if not l.startswith("#")]))


def printed_values():
    t = mv.OUT.read_text()
    return dict(re.findall(r"\\@namedef\{fv@([^}]*)\}\{([^}]*)\}", t))


def within(printed, value):
    """|value - printed| at most half a unit of the printed value's last digit."""
    dec = len(printed.split(".")[1]) if "." in printed else 0
    return abs(value - float(printed)) <= 0.5 * 10 ** -dec + 1e-12


def check_printed(files, pv):
    bad = []
    cells = read_rows(files["xsec16_cells.csv"])[1:]
    for r in cells:
        c = r[0]
        for k, (a, _, _) in enumerate(AXES):
            got = f"{float(r[1 + 2 * k]):g}--{float(r[2 + 2 * k]):g}"
            if pv.get(f"box-{c}-{a}") != got:
                bad.append(f"{c} {a}: the file gives {got}, the paper prints {pv.get(f'box-{c}-{a}')}")
    xs = {r[0]: r for r in read_rows(files["xsec16_cross_section.csv"])[1:]}
    for c, r in xs.items():
        if not within(pv[f"f-{c}"], float(r[1]) / 1e-40):
            bad.append(f"{c} xsec: the file gives {r[1]}, the paper prints {pv[f'f-{c}']} x 1e-40")
        if not within(pv[f"sig-C_total_resp-{c}"], 100 * float(r[3])):
            bad.append(f"{c} relative sigma: the file gives {r[3]}, the paper prints {pv[f'sig-C_total_resp-{c}']} %")
    cov = read_rows(files["xsec16_covariance.csv"])
    names = cov[0][1:]
    M = [[float(x) for x in r[1:]] for r in cov[1:]]
    for i in range(len(names)):
        for j in range(i):
            rho = M[i][j] / math.sqrt(M[i][i] * M[j][j])
            p = pv[f"corr-{names[i]}-{names[j]}"].replace("$-$", "-")
            if not within(p, rho):
                bad.append(f"corr {names[i]},{names[j]}: the file gives {rho:.4f}, the paper prints {p}")
    return bad


def check_side_csv(files):
    """A control from outside this script: the data product's own covariance CSV, written on the cluster by
    fd_data_product.py and pinned in the product's files_sha256, must agree with the file to 1e-9 relative."""
    rel = Path(mv.READOUTS["dp"][0]).with_name("fd_data_product_C_total_plus_C_resp.csv")
    raw = (mv.ROOT / rel).read_bytes()
    dp = mv.load()["dp"]
    assert hashlib.sha256(raw).hexdigest() == dp["files_sha256"][rel.name], "the side CSV differs from its pin"
    rows = read_rows(raw.decode())                    # a header row of cell names, then one row per cell
    assert rows[0][1:] == mv.CELLS and [r[0] for r in rows[1:]] == mv.CELLS
    side = [[float(x) for x in r[1:]] for r in rows[1:]]
    mine = [[float(x) for x in r[1:]] for r in read_rows(files["xsec16_covariance.csv"])[1:]]
    bad = [f"covariance [{i}][{j}] differs from the data product's own CSV" for i in range(16) for j in range(16)
           if abs(mine[i][j] - side[i][j]) > 1e-9 * max(abs(side[i][i]), abs(side[j][j]))]
    return bad[:3]


def check(files_on_disk=None):
    d = mv.load()
    gen = build(d)
    disk = files_on_disk or {n: (OUT / n).read_text() if (OUT / n).exists() else None for n in NAMES}
    bad = []
    for n in NAMES:
        if disk[n] is None:
            bad.append(f"{n}: missing"); continue
        sha = hashlib.sha256(disk[n].encode()).hexdigest()
        if not SUPP_PINS.get(n) or not sha.startswith(SUPP_PINS[n]):
            bad.append(f"{n}: sha256 {sha[:16]} is not its pin {SUPP_PINS.get(n)}")
        if disk[n] != gen[n]:
            bad.append(f"{n}: does not reproduce from the pinned data product")
    if not any(b.endswith("missing") for b in bad):
        bad += check_printed(disk, printed_values())
        bad += check_side_csv(disk)
    return bad


def main(argv):
    if not (mv.ROOT / mv.READOUTS["dp"][0]).exists():     # the standalone note repository has no readouts
        print("SUPPLEMENTAL :: SKIP (the pinned data product is not in this tree)")
        return 0
    if argv[:1] == ["--check"]:
        bad = check()
        for b in bad:
            print("  FAIL", b)
        print("SUPPLEMENTAL ::", "PASS (3 files pinned, reproduced from the data product and equal to the printed table to its precision)" if not bad else f"FAIL ({len(bad)})")
        return 1 if bad else 0
    if argv[:1] == ["--self-test"]:
        ok = not check()
        print(f"  {'ok  ' if ok else 'FAIL'} the committed files pass")
        base = {n: (OUT / n).read_text() for n in NAMES}
        r = read_rows(base["xsec16_cross_section.csv"])[1]
        plants = [("a changed cross section", "xsec16_cross_section.csv", r[1], f"{float(r[1]) * 1.01:.9e}"),
                  ("a changed edge", "xsec16_cells.csv", "\nR00,0,0.7,", "\nR00,0,0.8,"),
                  ("a changed covariance entry", "xsec16_covariance.csv", read_rows(base["xsec16_covariance.csv"])[2][1],
                   f"{float(read_rows(base['xsec16_covariance.csv'])[2][1]) * 1.5:.9e}")]
        for what, n, old, new in plants:
            assert base[n].count(old) >= 1, (what, old)
            planted = dict(base, **{n: base[n].replace(old, new, 1)})
            caught = bool(check(planted))
            ok &= caught
            print(f"  {'ok  ' if caught else 'FAIL'} {what} is refused")
        print("SUPPLEMENTAL SELF-TEST ::", "PASS" if ok else "FAIL")
        return 0 if ok else 1
    OUT.mkdir(exist_ok=True)
    for n, t in build(mv.load()).items():
        (OUT / n).write_text(t)
        print(n, hashlib.sha256(t.encode()).hexdigest()[:16])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

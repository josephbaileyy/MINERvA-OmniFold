#!/usr/bin/env python3
r"""Write note_release_labels.tex: the note's labels that the paper and the Supplement cite, from the note revision named
for release, so that their pointers into the note print that revision's numbers.

usage: make_note_labels.py --rev REV             write note_release_labels.tex from the note at REV
       make_note_labels.py --check REV           exit 1 unless the committed file is what --rev REV writes, byte for byte

Why (the director, 2026-11-10, journal-editor's cross-document review X1): main_paper.tex and main_supplement.tex read
the note's labels through xr-hyper from main_note.aux, i.e. from the copy of the note on this branch. That copy had fallen
behind the note to be released (#952), so four Supplement pointers printed the wrong table or section. They now
\input{note_release_labels} instead, which holds \newlabel{N-...} lines copied from the main_note.aux of the named
revision. The revision is built from `git archive REV docs/analysis-note` in a temporary directory (latexmk, as
build_all.sh builds the note); the worktree is never touched. Only the labels the four files cite (\ref*{N-...},
\nsec{...}, \napp{...}, outside comments) are written: a new pointer prints "??" and fails the build until this is rerun.

check_round.py checks that the file's revision is NOTE_RELEASE_REV, the revision named for release, and that every cited
label is in the file; its fill-test stage reruns this script with --check.
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "note_release_labels.tex"
SOURCES = ("paper_body.tex", "supplemental_body.tex", "main_paper.tex", "main_supplement.tex")
HEADER = "% note revision: "


def cited(d=HERE):
    """The note labels the paper and the Supplement cite, outside comments."""
    used = set()
    for f in SOURCES:
        t = "\n".join(re.sub(r"(?<!\\)%.*", "", l) for l in (d / f).read_text().split("\n"))
        used |= set(re.findall(r"\\ref\*?\{N-([^}#]+)\}", t))
        used |= set(re.findall(r"\\n(?:sec|app)\{([^}#]+)\}", t))
    return used


def aux_labels(aux):
    """label -> the full \\newlabel line of a main_note.aux (following \\@input)."""
    out = {}

    def rd(p):
        t = p.read_text(errors="replace")
        for m in re.finditer(r"\\@input\{([^}]*)\}", t):
            q = p.parent / m.group(1)
            if q.exists():
                rd(q)
        for line in t.split("\n"):
            m = re.match(r"\\newlabel\{([^}]*)\}(\{.*\})\s*$", line)
            if m:
                out[m.group(1)] = m.group(2)
    rd(aux)
    return out


def build(rev):
    full = subprocess.run(["git", "rev-parse", "--verify", rev + "^{commit}"], cwd=HERE, capture_output=True, text=True,
                          check=True).stdout.strip()
    with tempfile.TemporaryDirectory() as td:
        arch = subprocess.run(["git", "archive", full, "docs/analysis-note"], cwd=HERE.parents[1], capture_output=True, check=True)
        subprocess.run(["tar", "-x", "-C", td], input=arch.stdout, check=True)
        d = Path(td) / "docs/analysis-note"
        r = subprocess.run(["latexmk", "-pdf", "-g", "-interaction=nonstopmode", "-halt-on-error", "main_note.tex"],
                           cwd=d, capture_output=True, text=True, errors="replace")
        log = (d / "main_note.log").read_text(errors="replace") if (d / "main_note.log").exists() else ""
        if r.returncode != 0 or "There were undefined" in log:
            sys.exit(f"make_note_labels: the note at {full[:12]} did not build cleanly (rc {r.returncode})\n"
                     + r.stdout[-1500:])
        labels = aux_labels(d / "main_note.aux")
    need = sorted(cited())
    missing = [l for l in need if l not in labels]
    if missing:
        sys.exit(f"make_note_labels: cited labels not in the note at {full[:12]}: {missing}")
    lines = [HEADER + full,
             "% Generated by make_note_labels.py --rev " + full[:12] + "; do not edit by hand. The note's labels cited by"
             " paper_body.tex, supplemental_body.tex, main_paper.tex and main_supplement.tex, as \\newlabel lines of that"
             " revision's main_note.aux, prefixed N- as xr-hyper prefixed them.",
             "\\makeatletter"]
    lines += [f"\\newlabel{{N-{l}}}{labels[l]}" for l in need]
    lines += ["\\makeatother", ""]
    return full, "\n".join(lines)


def file_rev(text):
    m = re.match(re.escape(HEADER) + r"([0-9a-f]{40})", text)
    return m.group(1) if m else None


def main(a):
    if len(a) == 2 and a[0] == "--rev":
        full, text = build(a[1])
        OUT.write_text(text)
        print(f"NOTE-LABELS :: wrote {OUT.name}: {text.count(chr(92) + 'newlabel')} labels from the note at {full}")
        return 0
    if len(a) == 2 and a[0] == "--check":
        full, text = build(a[1])
        cur = OUT.read_text() if OUT.exists() else ""
        if cur != text:
            print(f"NOTE-LABELS :: FAIL: {OUT.name} is not what the note at {full[:12]} gives "
                  f"(file names {file_rev(cur)}); rerun make_note_labels.py --rev {full[:12]}")
            return 1
        print(f"NOTE-LABELS :: PASS: {OUT.name} equals the note at {full[:12]}'s labels")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

#!/usr/bin/env python3
r"""Write paper_labels.tex: the paper's labels that the Supplement cites, so that its pointers into the paper print the
paper's own numbers (the director's ruling (a), 2026-11-12, on style2's "give section numbers" item).

usage: make_paper_labels.py            write paper_labels.tex from this tree's paper (main_paper.tex, built in a temporary
                                       copy of the tracked files of docs/analysis-note, as they are in the worktree)
       make_paper_labels.py --check    exit 1 unless the committed file is what a fresh build writes, byte for byte

Why: main_supplement.tex may not load \externaldocument (check_round.py), so until now the Supplement named the paper's
sections in words ("the paper's section on what moves the retained prior"). A typed number would go stale silently when
the paper renumbers. Instead supplemental_body.tex writes \psec{<paper label>} (main_supplement.tex: "section~\ref*{P-..}")
and main_supplement.tex \input{paper_labels}, which holds the \newlabel{P-...} lines copied from main_paper.aux. Only the
labels the Supplement cites (\psec{...}, \ref*{P-...}, outside comments) are written: a new pointer prints "??" and fails
the build until this is rerun. The fill test runs --check, so a paper renumbering without a rerun fails loudly.
"""
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "paper_labels.tex"
SOURCES = ("supplemental_body.tex", "main_supplement.tex")
HEADER = "% paper labels from this tree's main_paper.tex"


def cited(d=HERE):
    """The paper labels the Supplement cites, outside comments."""
    used = set()
    for f in SOURCES:
        t = "\n".join(re.sub(r"(?<!\\)%.*", "", l) for l in (d / f).read_text().split("\n"))
        used |= set(re.findall(r"\\ref\*?\{P-([^}#]+)\}", t))
        used |= set(re.findall(r"\\psec\{([^}#]+)\}", t))
    return used


def aux_labels(aux):
    """label -> the \\newlabel argument text of main_paper.aux (following \\@input)."""
    out = {}

    def rd(p):
        t = p.read_text(errors="replace")
        for m in re.finditer(r"\\@input\{([^}]*)\}", t):
            q = p.parent / m.group(1)
            if q.exists():
                rd(q)
        for line in t.split("\n"):
            m = re.match(r"\\newlabel\{([^}]*)\}(\{.*\})\s*$", line)
            if m:
                out[m.group(1)] = m.group(2)
    rd(aux)
    return out


def build():
    files = subprocess.run(["git", "ls-files", "-z", "."], cwd=HERE, capture_output=True, check=True).stdout.split(b"\0")
    with tempfile.TemporaryDirectory() as td:
        d = Path(td)
        for f in (x.decode() for x in files if x):
            src = HERE / f
            if src.is_file():
                (d / f).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, d / f)
        r = subprocess.run(["latexmk", "-pdf", "-g", "-interaction=nonstopmode", "-halt-on-error", "main_paper.tex"],
                           cwd=d, capture_output=True, text=True, errors="replace")
        if r.returncode != 0:
            sys.exit(f"make_paper_labels: main_paper.tex did not build (rc {r.returncode})\n" + r.stdout[-1500:])
        labels = aux_labels(d / "main_paper.aux")
    need = sorted(cited())
    missing = [l for l in need if l not in labels]
    if missing:
        sys.exit(f"make_paper_labels: cited labels not in the paper: {missing}")
    lines = [HEADER,
             "% Generated by make_paper_labels.py; do not edit by hand. The paper's labels cited by supplemental_body.tex"
             " and main_supplement.tex, as \\newlabel lines of main_paper.aux, prefixed P-.",
             "\\makeatletter"]
    lines += [f"\\newlabel{{P-{l}}}{labels[l]}" for l in need]
    lines += ["\\makeatother", ""]
    return "\n".join(lines)


def main(a):
    if not a:
        text = build()
        OUT.write_text(text)
        print(f"PAPER-LABELS :: wrote {OUT.name}: {text.count(chr(92) + 'newlabel')} labels")
        return 0
    if a == ["--check"]:
        text = build()
        cur = OUT.read_text() if OUT.exists() else ""
        if cur != text:
            print(f"PAPER-LABELS :: FAIL: {OUT.name} is not what the paper in this tree gives; rerun make_paper_labels.py")
            return 1
        print(f"PAPER-LABELS :: PASS: {OUT.name} equals the paper's labels")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

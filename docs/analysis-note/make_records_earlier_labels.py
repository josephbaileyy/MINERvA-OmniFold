#!/usr/bin/env python3
"""Write records_earlier_labels.tex: the earlier draft's label numbers, for the records document's fallback.

usage: make_records_earlier_labels.py AUX SHA [--out records_earlier_labels.tex] [--check]

The records document (main_records.tex) quotes the posted note verbatim and resolves its references into the note
through main_note.aux (xr-hyper). Labels that the journal-voice rewrite (2026-11-21) removed from the note no longer
resolve there and printed as "??". The director's ruling (2026-11-21): resolve such a label against the earlier draft's
aux, marked "(earlier draft)", without rewriting any quotation. This script reads AUX, the main_note.aux of a build of
draft SHA, and writes one \\recearlierlabel{label}{number}{page} line per label. main_records.tex defines a label from
this file only if neither main_note.aux nor main_records.aux defines it, so a label present in the current note always
wins. --check exits 1 if the file on disk differs from what AUX and SHA would produce.
"""
import argparse
import hashlib
import sys
from pathlib import Path


def braced(s: str, i: int) -> tuple[str, int]:
    """The balanced {...} group starting at s[i] == '{', and the index after it."""
    assert s[i] == "{", s[i:i + 20]
    depth, j = 0, i
    while True:
        c = s[j]
        if c == "\\":
            j += 2
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return s[i + 1:j], j + 1
        j += 1


def labels(aux: str) -> list[tuple[str, str, str]]:
    out = []
    for line in aux.split("\n"):
        if not line.startswith("\\newlabel{"):
            continue
        name, k = braced(line, len("\\newlabel"))
        if "@" in name:
            continue
        body, _ = braced(line, k)
        num, k2 = braced(body, 0)
        page, _ = braced(body, k2)
        out.append((name, num, page))
    return out


def render(aux_path: Path, sha: str) -> str:
    raw = aux_path.read_bytes()
    rows = labels(raw.decode("utf-8"))
    head = [
        "% GENERATED by make_records_earlier_labels.py; do not edit. Records document only (main_records.tex).",
        f"% Source: main_note.aux of a build of draft {sha} (sha256 {hashlib.sha256(raw).hexdigest()[:16]}...), {len(rows)} labels.",
        "% A label is used only where neither the current note nor the records document defines it; it prints as",
        "% \"<number> (earlier draft)\" without a link.",
    ]
    return "\n".join(head + [f"\\recearlierlabel{{{n}}}{{{v}}}{{{p}}}" for n, v, p in rows]) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("aux", type=Path)
    ap.add_argument("sha")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent / "records_earlier_labels.tex")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render(a.aux, a.sha)
    if a.check:
        same = a.out.exists() and a.out.read_text(encoding="utf-8") == text
        print(f"RECORDS-EARLIER-LABELS :: {'PASS' if same else 'FAIL'}")
        return 0 if same else 1
    a.out.write_text(text, encoding="utf-8")
    print(f"wrote {a.out.name}: {text.count(chr(10)) - 4} labels")
    return 0


if __name__ == "__main__":
    sys.exit(main())

def orchestration_volume() -> str:
    """Prose lines and instrument lines under docs/orchestration, reported SEPARATELY.

    Never sum them. One number over the total makes deleting an instrument the cheapest way
    to pass a size target, and the instruments are what catch defects the prose does not.
    Reported here rather than in a document so the measurement costs no reading.

    Counts TRACKED files only. The first version walked the working tree with rglob and so
    counted other lanes' untracked strays: measured 42785 vs 42777 tracked with one lane's
    scratch present, meaning two lanes at the SAME commit printed different numbers and a
    quoted trend could show the layer growing when nothing had been written.

    THIS COSTS ABOUT 2x AND IS WORTH IT. Measured like-for-like, both arms doing the full
    line count, best of 5: the rglob walk 17.2 ms, this 33.5 ms. Roughly 16 ms per commit to
    make a published number reproducible across lanes is an obvious buy, but it is NOT free
    and nobody should reason from a claim that it was. The commit that introduced this
    function (d3cdc6d3) says "cheaper as well as reproducible" and that is FALSE: it
    compared `git ls-files` ALONE (18.3 ms) against the rglob path INCLUDING every
    `read_text` (28 ms). The reads are common to both arms and belong on both sides or
    neither; the honest enumeration-only pair is 18.3 ms of git against 2.1 ms of walk.
    Separately and still true: the 0.87 s that first ruled a git subprocess out of this
    function was `git log --since --name-only` walking HISTORY, which is a different command
    from an index read and did not generalize.

    Boundary, stated so this is not mistaken for a tree-of-record figure: it counts
    tracked PATHS with WORKING-TREE content. A lane's uncommitted edit to a tracked file
    still moves it; an untracked file no longer does.

    Non-raising: this is pre-commit check 10 for every lane. On any git failure it reports
    unavailable rather than falling back to a working-tree walk, because silently changing
    the measurement basis under the same label is worse than a missing number.
    """
    try:
        proc = subprocess.run(
            ["git", "-C", str(REPO), "ls-files", "-z", "--", "docs/orchestration"],
            capture_output=True, timeout=15, check=False)
        if proc.returncode != 0:
            return f"prose/instrument volume unavailable (ls-files rc={proc.returncode})"
        names = [n for n in proc.stdout.decode("utf-8", "replace").split("\0") if n]
        if not names:
            # PB-15: zero must be distinguishable from unmeasured. `git ls-files` exits 0 for
            # a path it knows nothing about, so an empty match set would otherwise print
            # "0 prose / 0 instrument" -- a measurement never made, and indistinguishable
            # from a genuinely empty layer. Fires on a rename of the path with no code change.
            return "prose/instrument volume unavailable (no tracked paths under docs/orchestration)"

        def lines(suffix: str) -> int:
            total = 0
            for name in names:
                if not name.endswith(suffix):
                    continue
                try:
                    total += len((REPO / name).read_text(
                        encoding="utf-8", errors="replace").splitlines())
                except OSError:
                    continue    # tracked but absent from the worktree: skip, never fail
            return total

        return (f"{lines('.md')} prose / {lines('.py')} instrument lines"
                f" over {len(names)} tracked files")
    except (OSError, subprocess.SubprocessError):
        return "prose/instrument volume unavailable"


def _label(path: Path) -> str:
    try:
        return str(path.relative_to(REPO))
    except ValueError:      # an entrypoint outside REPO must still be reportable
        return str(path)


def _words(path: Path) -> int:
    return len(re.findall(r"\S+", path.read_text(encoding="utf-8", errors="replace")))


def entrypoint_report() -> int:
    """Two populations, never one number.

    The PRESCRIBED PATH is what every session reads before it may act. The SEARCHED CORPUS is
    what a routed file contains, of which the route asks for one record. An earlier version of
    this function summed both and labelled the result "TOTAL prescribed default path": it
    reported 69009 where the route prescribes 12848, a 5.4x overstatement, because it counted
    the container and reported about the contents. Keeping the two apart is PB-15's rule --
    print the populations, and never a figure the instrument did not measure.
    """
    prescribed = 0
    print("PRESCRIBED PATH -- read in full by every session")
    for path in FULL_READ:
        if not path.exists():
            print(f"{'absent':>7}  {_label(path)}")
            continue
        words = _words(path)
        prescribed += words
        print(f"{words:7d}  {_label(path)}")
    print(f"{prescribed:7d}  subtotal")

    corpus = 0
    print("\nPLUS the exact cited record -- NOT the whole file (AGENTS.md, Evidence routes)")
    for path in ROW_ROUTED:
        if not path.exists():
            print(f"{'absent':>7}  {_label(path)}")
            continue
        full = _words(path)
        corpus += full
        rows = sorted(len(re.findall(r"\S+", line))
                      for line in path.read_text(encoding="utf-8", errors="replace").splitlines()
                      if re.match(r"^\| *OI-", line))
        if rows:
            med = rows[len(rows) // 2]
            print(f"{med:7d}  {_label(path)}  median record of {len(rows)} "
                  f"(min {rows[0]}, max {rows[-1]})")
            print(f"{prescribed + med:7d}  PRESCRIBED PATH TOTAL, median record")
            print(f"{prescribed + rows[-1]:7d}  PRESCRIBED PATH TOTAL, largest record")
        else:
            print(f"{'n/a':>7}  {_label(path)}  no OI records matched -- cannot price a record")

    print("\nSEARCHED CORPUS -- present in routed files, not prescribed reading")
    for path in ROW_ROUTED:
        if path.exists():
            print(f"{_words(path):7d}  {_label(path)} in full")
    print(f"{prescribed + corpus:7d}  routed corpus total")
    return 0



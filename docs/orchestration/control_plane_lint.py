def registry_coverage(open_items_path: Path = OPEN_ITEMS,
                      work_path: Path = WORK_ITEMS) -> tuple[int, int, int, Counter, Counter]:
    rows = [RegisterRow(**row) for row in read_tsv(work_path, REGISTER_COLUMNS)]
    records = declared_routing(open_items_path, {row.item: row for row in rows})
    promoted = {row.source_record for row in rows if row.promotion == "promoted"}

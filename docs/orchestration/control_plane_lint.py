OWNERS = CONTROL / "owners.tsv"
WORK_ITEMS = CONTROL / "work-items.tsv"
PLAYBOOK_SOURCE = CONTROL / "playbook.tsv"
SOURCE_INVENTORY = CONTROL / "source-record-inventory.tsv"
CURRENT = REPO / "docs/CURRENT_WORK.md"
OVERFLOW = REPO / "docs/CURRENT_WORK_OVERFLOW.md"
BACKLOG = REPO / "docs/CURRENT_WORK_BACKLOG.md"
PLAYBOOK = REPO / "docs/orchestration/PLAYBOOK.md"

def markdown_bullets(section: str) -> tuple[list[str], bool]:
    """Return normalized bullets and whether non-bullet prose/comments were present."""
    bullets: list[str] = []
    invalid = False
    for raw in section.splitlines():
        if not raw.strip():
            continue
        if raw.startswith("- "):
            bullets.append(raw[2:].strip())
        elif raw.startswith("  ") and bullets:
            bullets[-1] += " " + raw.strip()
        else:
            invalid = True
    return bullets, invalid


def bootstrap_contract_errors(agents: str, claude: str, playbook: str) -> list[str]:
    """Validate the thin shared front door without requiring duplicated bootstrap prose."""
    errors: list[str] = []
    if len(agents.splitlines()) > 150:
        errors.append("AGENTS.md exceeds the 150-line front-door cap")
    if len(claude.splitlines()) > 20:
        errors.append("CLAUDE.md exceeds the 20-line bootstrap cap")
    for required in ("docs/CURRENT_WORK.md", "docs/orchestration/PLAYBOOK.md"):
        if required not in agents:
            errors.append(f"AGENTS.md does not route to {required}")
    claude_blocks = [block for block in re.split(r"\n\s*\n", claude)
                     if block.strip() and not block.lstrip().startswith("#")]
    claude_paragraphs = [" ".join(block.split()) for block in claude_blocks]
    if not claude_paragraphs or claude_paragraphs[0] != CANONICAL_CLAUDE_ROUTE:
        errors.append("CLAUDE.md does not begin with the exact canonical AGENTS.md route")
    claude_bullets, invalid_claude = markdown_bullets("\n\n".join(claude_blocks[1:]))
    if invalid_claude or tuple(claude_bullets) != CANONICAL_CLAUDE_BULLETS:
        errors.append("CLAUDE.md bootstrap rules do not match the canonical bullet contract")
    if claude.count("AGENTS.md") != 2:
        errors.append("CLAUDE.md must contain exactly its two canonical AGENTS.md routes")
    integrity = re.search(
        r"^## Minimal integrity rules\n(.*?)(?=^## )", agents, re.MULTILINE | re.DOTALL)
    if not integrity:
        errors.append("AGENTS.md has no bounded Minimal integrity rules section")
    integrity_text = integrity.group(1) if integrity else ""
    integrity_bullets, invalid_integrity = markdown_bullets(integrity_text)
    if invalid_integrity or tuple(integrity_bullets) != CANONICAL_INTEGRITY_RULES:
        errors.append("AGENTS.md Minimal integrity rules do not match the canonical bullet contract")
    active_bens = set(re.findall(r"BEN-\d{3}", playbook))
    duplicated_bens = sorted(active_bens & set(re.findall(
        r"BEN-\d{3}", integrity_text)))
    if duplicated_bens:
        errors.append("AGENTS.md duplicates BEN-backed playbook rules in Minimal integrity rules: "
                      + ", ".join(duplicated_bens))
    return errors


def check_or_write(write: bool, adoption: bool = False) -> int:
    outputs, errors, policy, drifted = generated_outputs()
    if adoption:
        errors.extend(adoption_errors(policy))
    for path, expected in outputs.items():
        if write:
            path.write_text(expected, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != expected:
            errors.append(f"generated output stale: {path.relative_to(REPO)}; run --write")
    errors.extend(bootstrap_contract_errors(
        AGENTS.read_text(encoding="utf-8"), CLAUDE.read_text(encoding="utf-8"), outputs[PLAYBOOK]))
    catalog = (REPO / "docs/orchestration/CATALOG.md").read_text(encoding="utf-8")
    for required in ("CURRENT_WORK.md", "CURRENT_WORK_OVERFLOW.md", "CURRENT_WORK_BACKLOG.md",
                     "PLAYBOOK.md", "control-plane/policy.json", "source-record-inventory.tsv"):
        if required not in catalog:
            errors.append(f"CATALOG.md does not route to {required}")
    if errors:
        for error in errors:
            print(f"CONTROL-PLANE FAIL: {error}")
        return 1
    verb = "WROTE" if write else "PASS"
    selected = len(re.findall(r"^\| OI-", outputs[CURRENT], re.MULTILINE))
    overflow = len(re.findall(r"^\| OI-", outputs[OVERFLOW], re.MULTILINE))
    backlog = len(re.findall(r"^\| OI-", outputs[BACKLOG], re.MULTILINE))
    active_pb = len(re.findall(r"^\| PB-", outputs[PLAYBOOK], re.MULTILINE))
    inventory = len(outputs[SOURCE_INVENTORY].splitlines()) - 1
    print(f"CONTROL-PLANE {verb}: {selected} selected; {overflow} overflow; {backlog} backlog; "
          f"{inventory} source records; {active_pb} playbook rules; "
          f"{drifted} state cells changed since declaration; "
          f"{orchestration_volume()}")
    return 0



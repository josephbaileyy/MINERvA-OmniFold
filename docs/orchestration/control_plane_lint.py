def coverage_report() -> int:
    total, promoted, backlog, counts = registry_coverage()
    print(f"CONTROL-PLANE COVERAGE: {total}/{total} source records classified")
    print(f"promoted source records: {promoted}; active unpromoted backlog: {backlog}")
    for (lifecycle, queue), count in sorted(counts.items()):
        print(f"{lifecycle:8} {queue:16} {count}")
    return 0


def entrypoint_report() -> int:
    total = 0
    for path in ENTRYPOINTS:
        words = len(re.findall(r"\S+", path.read_text(encoding="utf-8")))
        total += words
        print(f"{words:7d}  {path.relative_to(REPO)}")
    print(f"{total:7d}  TOTAL prescribed default path")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true")
    group.add_argument("--coverage-report", action="store_true")
    group.add_argument("--entrypoint-report", action="store_true")
    group.add_argument("--self-test", action="store_true")
    group.add_argument("--adoption-check", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    if args.coverage_report:
        return coverage_report()
    if args.entrypoint_report:
        return entrypoint_report()
    return check_or_write(args.write, args.adoption_check)


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Generate and validate the bounded current-work and active-playbook surfaces.

Humans declare ranking, ownership, and active lessons. Explicit leading OI state language is classified
by checked-in ordered rules with a safe-active default. This program inventories every source record,
resolves unassigned ownership, ranks promoted leaves, renders backlog/overflow, and promotes playbook
rules. It never edits OPEN_ITEMS.md or FINDINGS.md.

Default / --check: compare generated bytes with tracked outputs.
--write: rewrite generated outputs.
--coverage-report: report source-record migration coverage without changing files.
--entrypoint-report: measure the two platform bootstrap documents.
--adoption-check: additionally require full-registry coverage and canonical-adoption approval.
--self-test: exercise ranking, cap overflow, owner escalation, and playbook retirement.
"""

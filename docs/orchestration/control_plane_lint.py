CLAUDE = REPO / "CLAUDE.md"
ENTRYPOINTS = (CLAUDE, AGENTS)

OWNER_COLUMNS = ("owner_id", "display_name", "accountable_holder", "escalation", "assignment_state")
WORK_COLUMNS = ("item", "source_record", "queue_override", "owner_id", "impact", "urgency",
                "next_action", "evidence")
INVENTORY_COLUMNS = ("source_record", "lifecycle", "queue", "classification_rule",
                     "source_row_sha256", "state_prefix")
PLAYBOOK_COLUMNS = ("key", "state", "operating_rule", "observable_check", "evidence",
                    "retirement_reason")
ALLOWED_QUEUES = {"NOW", "WAITING-JOSEPH", "BLOCKED-EXTERNAL"}
ALLOWED_STATES = {"active", "deferred", "retired"}


@dataclass(frozen=True)
class WorkRow:
    item: str
    queue: str
    owner: str
    action: str
    evidence: str
    basis: str
    score: int


@dataclass(frozen=True)
class SourceRecord:
    key: str
    lifecycle: str
    queue: str
    rule: str
    row_sha256: str
    state_prefix: str


def read_tsv(path: Path, columns: tuple[str, ...]) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        if tuple(reader.fieldnames or ()) != columns:
            raise ValueError(f"{path}: columns {reader.fieldnames!r}, expected {list(columns)!r}")
        return [{key: (value or "").strip() for key, value in row.items()} for row in reader]


def natural_item_key(item: str) -> tuple[int, str]:
    match = re.fullmatch(r"OI-(\d+)(?:\(([a-z])\))?", item)
    if not match:
        raise ValueError(f"invalid item key {item!r}; expected OI-N or OI-N(a)")
    return int(match.group(1)), match.group(2) or ""


def parent_item(item: str) -> str:
    match = re.match(r"OI-\d+", item)
    if not match:
        raise ValueError(f"invalid item key {item!r}")
    return match.group(0)


def source_oi_rows(path: Path) -> list[tuple[str, str, str]]:
    """Return (occurrence-key, state-prefix, exact-row) without pretending malformed Markdown is CSV."""
    matches: list[tuple[str, str, str]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^\|\s*(OI-\d+)\s*\|\s*(.*?)\s*\|", line)
        if match:
            matches.append((match.group(1), match.group(2), line))
    totals = Counter(item for item, _, _ in matches)
    seen: Counter[str] = Counter()
    records: list[tuple[str, str, str]] = []
    for item, state, line in matches:
        seen[item] += 1
        key = f"{item}#{seen[item]}" if totals[item] > 1 else item
        records.append((key, state, line))
    return records


def source_oi_records(path: Path) -> list[str]:
    return [key for key, _, _ in source_oi_rows(path)]


def normalize_state(state: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[*`~]", "", state)).strip().upper()


def classify_source_records(path: Path, policy: dict) -> list[SourceRecord]:
    config = policy["source_classification"]
    overrides = config.get("overrides", {})
    rules = config["ordered_rules"]
    default = config["default"]
    records: list[SourceRecord] = []
    for key, state, exact_row in source_oi_rows(path):
        base = key.split("#", 1)[0]
        decision = overrides.get(key, overrides.get(base))
        if decision is None:
            normalized = normalize_state(state)
            decision = next((rule for rule in rules if re.search(rule["pattern"], normalized)), default)
        lifecycle, queue = decision["lifecycle"], decision["queue"]
        rule = decision.get("rule", decision.get("name", "unnamed-rule"))
        prefix = re.sub(r"\s+", " ", re.sub(r"[*`~]", "", state)).strip()[:120].rstrip()
        records.append(SourceRecord(key, lifecycle, queue, rule,
                                    hashlib.sha256(exact_row.encode()).hexdigest(), prefix))
    return records


def render_inventory(records: list[SourceRecord]) -> str:
    lines = ["\t".join(INVENTORY_COLUMNS)]
    for row in records:
        values = (row.key, row.lifecycle, row.queue, row.rule, row.row_sha256, row.state_prefix)
        lines.append("\t".join(values))
    return "\n".join(lines) + "\n"


def source_ben_ids(paths: tuple[Path, ...]) -> set[str]:
    text = "\n".join(path.read_text(encoding="utf-8") for path in paths)
    return set(re.findall(r"^\|\s*(BEN-\d{3})\s*\|", text, re.MULTILINE))


def load_model(policy_path: Path = POLICY, owners_path: Path = OWNERS,
               work_path: Path = WORK_ITEMS, playbook_path: Path = PLAYBOOK_SOURCE,
               open_items_path: Path = OPEN_ITEMS,
               findings_paths: tuple[Path, ...] = (FINDINGS,)):
    errors: list[str] = []
    policy = json.loads(policy_path.read_text(encoding="utf-8"))
    owner_rows = read_tsv(owners_path, OWNER_COLUMNS)
    work_rows = read_tsv(work_path, WORK_COLUMNS)
    playbook_rows = read_tsv(playbook_path, PLAYBOOK_COLUMNS)
    source_records = classify_source_records(open_items_path, policy)
    record_by_key = {record.key: record for record in source_records}
    oi_record_set = set(record_by_key)
    oi_ids = {record.split("#", 1)[0] for record in oi_record_set}
    ben_ids = source_ben_ids(findings_paths)

    classification = policy["source_classification"]
    decisions = list(classification["ordered_rules"]) + [classification["default"]]
    decisions += list(classification.get("overrides", {}).values())
    for decision in decisions:
        if decision.get("lifecycle") not in ALLOWED_STATES:
            errors.append(f"classification decision {decision.get('name', decision.get('rule'))!r} "
                          "has invalid lifecycle")
        if decision.get("queue") not in ALLOWED_QUEUES | {"-"}:
            errors.append(f"classification decision {decision.get('name', decision.get('rule'))!r} "
                          "has invalid queue")
    for key in classification.get("overrides", {}):
        if key not in oi_record_set and key.split("#", 1)[0] not in oi_ids:
            errors.append(f"classification override targets missing source record {key}")
    for rule in classification["ordered_rules"]:
        try:
            re.compile(rule["pattern"])
        except re.error as exc:
            errors.append(f"classification rule {rule.get('name')!r} has invalid regex: {exc}")
    for record in source_records:
        if record.lifecycle not in ALLOWED_STATES:
            errors.append(f"{record.key}: classification produced invalid lifecycle {record.lifecycle!r}")
        if record.lifecycle == "active" and record.queue not in ALLOWED_QUEUES:
            errors.append(f"{record.key}: active classification has invalid queue {record.queue!r}")
        if record.lifecycle != "active" and record.queue != "-":
            errors.append(f"{record.key}: inactive classification must use queue '-'")

    owners: dict[str, dict[str, str]] = {}
    for row in owner_rows:
        oid = row["owner_id"]
        if not oid or oid in owners:
            errors.append(f"duplicate or empty owner_id: {oid!r}")
            continue
        if row["assignment_state"] not in {"assigned", "unassigned"}:
            errors.append(f"{oid}: assignment_state must be assigned/unassigned")
        if row["assignment_state"] == "assigned" and row["accountable_holder"] in {"", "-"}:
            errors.append(f"{oid}: assigned role has no accountable_holder")
        if row["assignment_state"] == "unassigned" and row["escalation"] in {"", "-"}:
            errors.append(f"{oid}: unassigned role has no escalation")
        owners[oid] = row

    seen_items: set[str] = set()
    registered_records: set[str] = set()
    active: list[WorkRow] = []
    for row in work_rows:
        item = row["item"]
        try:
            natural_item_key(item)
        except ValueError as exc:
            errors.append(str(exc))
            continue
        if item in seen_items:
            errors.append(f"duplicate work item: {item}")
        seen_items.add(item)
        source_record = row["source_record"]
        if not re.fullmatch(r"OI-\d+(?:#[1-9]\d*)?", source_record):
            errors.append(f"{item}: invalid source_record {source_record!r}")
        elif source_record not in oi_record_set:
            errors.append(f"{item}: source_record {source_record!r} is absent from OPEN_ITEMS.md")
        elif source_record.split("#", 1)[0] != parent_item(item):
            errors.append(f"{item}: source_record {source_record!r} has a different parent id")
        registered_records.add(source_record)
        if parent_item(item) not in oi_ids:
            errors.append(f"{item}: no parent row in OPEN_ITEMS.md")
        owner = owners.get(row["owner_id"])
        if owner is None:
            errors.append(f"{item}: unknown owner_id {row['owner_id']!r}")
            continue
        source = record_by_key.get(source_record)
        if source is None:
            continue
        if source.lifecycle != "active":
            errors.append(f"{item}: promoted leaf points to {source.lifecycle} source {source_record}")
            continue
        override = row["queue_override"]
        if override not in ALLOWED_QUEUES | {"-"}:
            errors.append(f"{item}: invalid queue_override {override!r}")
            continue
        queue = source.queue if override == "-" else override
        impact = row["impact"]
        urgency = row["urgency"]
        if impact not in policy["impact_weights"]:
            errors.append(f"{item}: invalid impact {impact!r}")
            continue
        if urgency not in policy["urgency_weights"]:
            errors.append(f"{item}: invalid urgency {urgency!r}")
            continue
        action = row["next_action"]
        if not action or len(action) > 260:
            errors.append(f"{item}: next_action must be 1-260 characters")
        if "OPEN_ITEMS.md" not in row["evidence"]:
            errors.append(f"{item}: evidence must route to OPEN_ITEMS.md")
        if owner["assignment_state"] == "unassigned":
            queue = policy["unassigned_owner_queue"]
            if action:
                action = policy["unassigned_action_prefix"] + action[0].lower() + action[1:]
            owner_display = f"{owner['display_name']} → {owner['escalation']}"
        else:
            owner_display = owner["display_name"]
        score = (policy["impact_weights"][impact] + policy["urgency_weights"][urgency]
                 + policy["queue_weights"][queue])
        active.append(WorkRow(item, queue, owner_display, action, row["evidence"],
                              f"{impact}/{urgency}", score))

    seen_pb: set[str] = set()
    active_pb: list[dict[str, str]] = []
    inactive_pb: list[dict[str, str]] = []
    for row in playbook_rows:
        key = row["key"]
        if not re.fullmatch(r"PB-\d{2}", key):
            errors.append(f"invalid playbook key: {key!r}")
        if key in seen_pb:
            errors.append(f"duplicate playbook key: {key}")
        seen_pb.add(key)
        if row["state"] not in {"active", "retired"}:
            errors.append(f"{key}: state must be active/retired")
            continue
        cited = re.findall(r"BEN-\d{3}", row["evidence"])
        if not cited:
            errors.append(f"{key}: cites no BEN evidence")
        for ben in cited:
            if ben not in ben_ids:
                errors.append(f"{key}: cites missing {ben}")
        if not row["operating_rule"] or not row["observable_check"]:
            errors.append(f"{key}: rule and observable_check are required")
        if row["state"] == "active":
            active_pb.append(row)
        else:
            if row["retirement_reason"] in {"", "-"}:
                errors.append(f"{key}: retired rule needs retirement_reason")
            inactive_pb.append(row)

    active.sort(key=lambda row: (-row.score, natural_item_key(row.item)))
    active_pb.sort(key=lambda row: int(row["key"].split("-")[1]))
    minimum, cap = policy["current_work_min"], policy["current_work_cap"]
    if len(active) < minimum:
        errors.append(f"active work has {len(active)} rows; minimum is {minimum}")
    if not policy["playbook_min"] <= len(active_pb) <= policy["playbook_cap"]:
        errors.append(f"active playbook has {len(active_pb)} rows; allowed range is "
                      f"{policy['playbook_min']}-{policy['playbook_cap']}")
    selected, overflow = active[:cap], active[cap:]
    unpromoted = [record for record in source_records
                  if record.lifecycle == "active" and record.key not in registered_records]
    return policy, selected, overflow, active_pb, inactive_pb, source_records, unpromoted, errors


def render_current(policy: dict, selected: list[WorkRow]) -> str:
    mode = "CANONICAL" if policy.get("canonical_adoption_allowed") else "PROTOTYPE"
    lines = [
        "# Current work — bounded attention queue", "",
        f"> **{mode}; GENERATED by `docs/orchestration/control_plane_lint.py --write`. Do not hand-edit.**",
        "> Sources: `control-plane/policy.json`, `owners.tsv`, and `work-items.tsv`. Full scientific",
        "> state and evidence remain in `docs/OPEN_ITEMS.md`; this view is authoritative only for routing.", "",
        f"Policy selects the top {policy['current_work_cap']} promoted leaves by impact, urgency,",
        "and effective queue. Unassigned roles are automatically routed to `WAITING-JOSEPH`. Ties use",
        "numeric OI id and sub-item. Source lifecycle and queue are derived from explicit OI state",
        "language; terminal and deferred records never enter this page.", "",
        "| item | queue | accountable owner | basis | next action | evidence route |",
        "|---|---|---|---|---|---|",
    ]
    for row in selected:
        lines.append(f"| {row.item} | {row.queue} | {row.owner} | {row.basis} | {row.action} | {row.evidence} |")
    lines += ["", "## Machine-enforced contract", "",
              f"- Rendered membership is capped at {policy['current_work_cap']}; overflow is generated at "
              "`docs/CURRENT_WORK_OVERFLOW.md`.",
              "- An unassigned owner cannot render as `NOW`.",
              "- Queue order and tie-breaking come only from the checked-in policy, never table position.",
              "- `policy.json` classifies explicit source state; humans declare only promotion, impact,",
              "  urgency, and accountability in `work-items.tsv`."]
    return "\n".join(lines) + "\n"


def render_overflow(policy: dict, overflow: list[WorkRow]) -> str:
    lines = ["# Current-work overflow", "",
             "> GENERATED by `docs/orchestration/control_plane_lint.py --write`. Do not hand-edit.", "",
             f"Items below were eligible but fell below the top-{policy['current_work_cap']} cutoff. "
             "They are not terminal and are not silently deferred.", "",
             "| item | effective queue | owner | basis | score | evidence |",
             "|---|---|---|---|---:|---|"]
    if overflow:
        for row in overflow:
            lines.append(f"| {row.item} | {row.queue} | {row.owner} | {row.basis} | {row.score} | {row.evidence} |")
    else:
        lines.append("| — | — | — | — | — | No eligible item currently falls below the cap. |")
    return "\n".join(lines) + "\n"


def render_backlog(records: list[SourceRecord]) -> str:
    lines = ["# Unpromoted open-item backlog", "",
             "> GENERATED by `docs/orchestration/control_plane_lint.py --write`. Do not hand-edit.", "",
             "These source records classify as active but have no promoted actionable leaf. They remain",
             "visible here and in `OPEN_ITEMS.md`; omission from `CURRENT_WORK.md` is not retirement.", "",
             "| source record | derived queue | classification rule | source state prefix |",
             "|---|---|---|---|"]
    if records:
        for row in records:
            prefix = row.state_prefix.replace("|", "\\|")
            lines.append(f"| {row.key} | {row.queue} | {row.rule} | {prefix} |")
    else:
        lines.append("| — | — | — | Every active source record has a promoted leaf. |")
    return "\n".join(lines) + "\n"


def render_playbook(policy: dict, rows: list[dict[str, str]]) -> str:
    mode = "CANONICAL" if policy.get("canonical_adoption_allowed") else "PROTOTYPE"
    lines = ["# Active campaign playbook", "",
             f"> **{mode}; GENERATED by `docs/orchestration/control_plane_lint.py --write`. Do not hand-edit.**",
             "> Source: `control-plane/playbook.tsv`. `FINDINGS.md` remains the evidence casebook and is",
             "> opened on demand by BEN id.", "",
             "| key | operating rule | executable or observable check | evidence |",
             "|---|---|---|---|"]
    for row in rows:
        lines.append(f"| {row['key']} | {row['operating_rule']} | {row['observable_check']} | {row['evidence']} |")
    lines += ["", "## Promotion and retirement", "",
              "- Search the casebook first; a new BEN must change a check, rule, or established scope.",
              f"- At most {policy['playbook_cap']} rules may be active. Promoting another rule at the cap "
              "requires retiring or consolidating one in the same source change.",
              "- Retirement preserves the TSV row, BEN evidence, and a non-empty reason; it removes only",
              "  default-read status, not history."]
    return "\n".join(lines) + "\n"


def generated_outputs(**paths) -> tuple[dict[Path, str], list[str], dict]:
    policy, selected, overflow, playbook, _, source_records, unpromoted, errors = load_model(**paths)
    outputs = {CURRENT: render_current(policy, selected),
               OVERFLOW: render_overflow(policy, overflow),
               BACKLOG: render_backlog(unpromoted),
               SOURCE_INVENTORY: render_inventory(source_records),
               PLAYBOOK: render_playbook(policy, playbook)}
    return outputs, errors, policy


def registry_coverage(open_items_path: Path = OPEN_ITEMS,
                      work_path: Path = WORK_ITEMS) -> tuple[int, int, int, Counter]:
    policy = json.loads(POLICY.read_text(encoding="utf-8"))
    records = classify_source_records(open_items_path, policy)
    promoted = {row["source_record"] for row in read_tsv(work_path, WORK_COLUMNS)}
    active = {record.key for record in records if record.lifecycle == "active"}
    counts = Counter((record.lifecycle, record.queue) for record in records)
    return len(records), len(promoted), len(active - promoted), counts


def adoption_errors(policy: dict) -> list[str]:
    errors = []
    if not policy.get("canonical_adoption_allowed"):
        errors.append("canonical adoption is disabled in policy.json")
    if policy.get("registry_scope") != "all-open-items-records":
        errors.append("registry_scope must be all-open-items-records before adoption")
    return errors



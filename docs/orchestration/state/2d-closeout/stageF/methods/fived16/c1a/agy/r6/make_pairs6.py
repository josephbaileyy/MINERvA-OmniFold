"""Build agy's pairs for PRD read r6 (director, 2026-10-28, accepting 1bcccc38): the three composites as they print
(Q1 A1, Q2 A2, Q3 H1, from prd-read/r6/input.txt) and the two rater alternatives that passed r6's truth column (Q4: sol2
r1's A1/A2 form; Q5: sol2 r2's H1 form, from prd-read/r6/runs/). BEFORE is pass 5's facts block, read from
../pairs5.txt (generated by make_pairs.py from the readout, the report and the declaration; nothing retyped). The
control plants one strengthening in Q1, Q3, Q4 and Q5; Q2 is unplanted, as a check.
usage: python3 make_pairs6.py <worktree> <outdir>"""
import re, sys
W, O = sys.argv[1], sys.argv[2]
M = f"{W}/docs/orchestration/state/2d-closeout/stageF/methods/fived16"
before = re.search(r"^BEFORE: (.*)$", open(f"{M}/c1a/agy/pairs5.txt").read(), re.M).group(1)
new = dict(re.findall(r"^(A1|A2|H1) \([^)]*\)\. OLD: .*\nNEW: (.*)$", open(f"{M}/prd-read/r6/input.txt").read(), re.M))


def form(run, item):
    t = open(f"{M}/prd-read/r6/runs/{run}").read()
    return re.search(item + r": VERDICT: SHORTEN\nSHORTER-FORM: (.*)", t).group(1)


after = [new["A1"], new["A2"], new["H1"], form("PR6__r1__sol2.txt", "A1"), form("PR6__r2__sol2.txt", "H1")]
assert form("PR6__r1__sol2.txt", "A1") == form("PR6__r1__sol2.txt", "A2"), "sol2 r1's A1 and A2 forms differ"
plants = {0: ("two held-out GENIE v3 truths", "two held-out truths"),
          2: ("They provide partial evidence and are not independent tests.", "They are two independent tests."),
          3: ("but do not assess interval widths", "and confirm interval widths"),
          4: ("These tests provide partial evidence and are not independent.", "These are two independent tests.")}
for name, plant in (("pairs.txt", False), ("pairs-control.txt", True)):
    out = []
    for n, a in enumerate(after):
        if plant and n in plants:
            assert a.count(plants[n][0]) == 1, (n, plants[n][0])
            a = a.replace(*plants[n])
        out.append(f"Q{n + 1}.\nBEFORE: {before}\nAFTER: {a}\n")
    open(f"{O}/{name}", "w").write("(Q3 and Q5 are additions to the paper. A reference to a table or section is a "
                                   "cross-reference, not a claim about the study, and is not to be judged.)\n\n" + "\n".join(out))
print("pairs written; control plants in Q1, Q3, Q4, Q5")

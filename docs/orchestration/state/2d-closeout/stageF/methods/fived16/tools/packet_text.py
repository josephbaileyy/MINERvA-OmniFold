"""Print, with every \\fvval{key} resolved to its value, (1) the paper's two FIVED16 blocks and the note chapter's prose,
and (2) every printed sentence that is new against base 8b0f83fd, by file. Scratch tool for the wording packet."""
import importlib.util
import re
import sys

T, BASE, OUT = sys.argv[1:4]          # the tree's docs/analysis-note, the base copy, the output file
spec = importlib.util.spec_from_file_location(
    "cl", T + "/../orchestration/state/2d-closeout/stageF/methods/fived16/check_ledger.py")
cl = importlib.util.module_from_spec(spec); spec.loader.exec_module(cl)
vals = dict(re.findall(r"\\@namedef\{fv@([^}]*)\}\{(.*)\}$", open(T + "/values_fived16.tex").read(), re.M))


def resolve(s):
    s = re.sub(r"\\fvval\{([^}]*)\}", lambda m: vals[m.group(1)], s)
    return s


def prose(src):
    """Paragraph lines of a source, comments stripped, tables and floats dropped."""
    out, skip = [], 0
    for line in src.splitlines():
        if re.match(r"\s*\\begin\{(table\*?|figure\*?)\}", line): skip += 1
        if skip == 0:
            l = re.sub(r"(?<!\\)%.*", "", line).strip()
            if l and not l.startswith("\\label") and not l.startswith("\\end"):
                out.append(resolve(l))
        if re.match(r"\s*\\end\{(table\*?|figure\*?)\}", line): skip = max(0, skip - 1)
    return out


L = ["# Printed wording, values resolved (generated by packet_text.py)", ""]
pb = open(T + "/paper_body.tex").read()
L += ["## A. The paper's new subsections (paper_body.tex, FIVED16 blocks)", ""]
for m in re.finditer(r"% FIVED16-BEGIN[^\n]*\n(.*?)% FIVED16-END", pb, re.S):
    L += [f"> {p}" for p in prose(m.group(1))] + ["<!-- absence-ok: quotes the note's and paper's printed text as the wording packet's record; each claim carries its Search line in the source -->", ""]
L += ["## B. The note's new chapter (sec_fived16.tex), prose only (tables in the PDF)", ""]
L += [f"> {p}" for p in prose(open(T + "/sec_fived16.tex").read())] + ["<!-- absence-ok: quotes the note's and paper's printed text as the wording packet's record; each claim carries its Search line in the source -->", ""]
L += ["## C. Every changed printed sentence of the existing sources, as it now reads", "",
      "Each is a sentence that does not print at base 8b0f83fd. The ledger (`ledger.md`) gives each one's row, the "
      "base sentence it replaces and its probes.", ""]
for f in sorted(cl.PREFIX):
    if f == "sec_fived16.tex":
        continue
    try:
        cur, old = open(f"{T}/{f}").read(), open(f"{BASE}/{f}").read()
    except FileNotFoundError:
        continue
    if f == "paper_body.tex":
        cur = re.sub(r"% FIVED16-BEGIN.*?% FIVED16-END", "", cur, flags=re.S)
    o = cl.printed(old)
    new = [s for s in cl.sentences(cl.printed(cur)) if s not in o]
    if new:
        L += [f"### {f} ({len(new)})", ""] + [f"- {resolve(s)}" for s in new] + ["<!-- absence-ok: quotes the note's and paper's printed text as the wording packet's record; each claim carries its Search line in the source -->", ""]
open(OUT, "w").write("\n".join(L) + "\n")
print("wrote", OUT, sum(1 for l in L if l.startswith("- ")), "changed sentences")

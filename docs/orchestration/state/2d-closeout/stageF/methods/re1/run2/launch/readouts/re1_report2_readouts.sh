#!/bin/bash
# RE-1 run 2, review round: re1_c2_cells.py (per-cell C2/D2 table, SE counts) and re1_report2_extras.py (3D totals,
# marginal scatter, 5D (c)-(a) in trunk sigma), on the login node, pinned, through the OI-136 guard.
#   re1_report2_readouts.sh <deploy checkout at the commit that adds both scripts>
set -eo pipefail
C=$(cd "$1" && pwd)
[ -z "$(git -C "$C" status --porcelain)" ] || { echo "deploy $C is not clean"; exit 2; }
source $C/docs/orchestration/state/2d-closeout/stageF/methods/re1/run2/launch/re1_env.sh
source $C/docs/orchestration/state/2d-closeout/stageF/methods/re1/run2/launch/re1_f_env.sh
source $A/setup_salloc_env.sh >/dev/null 2>&1
export TMPDIR=$B/tmp; R=$O/readouts
sha() { sha256sum "$1" | cut -d' ' -f1; }
COV=/global/cfs/cdirs/m3246/josephrb/2d-closeout-stageC-production-20261015/results/s5/production_cov.npz
Q=/global/cfs/cdirs/m3246/josephrb/2d-closeout-playlist-combination-20261017/s5_plus_playlist.npz
g() { local label=$1; shift; taskset -c 8-11 python $C/nd-unfolding/mnv_guarded_run.py --expect-root $C --label $label \
        --inventory $O/inventory/$label.jsonl -- "$@"; }
for p in $R/c2_d2_cells_regen.tsv $R/c2_cells.json $R/report2_extras.json; do [ ! -e $p ] || { echo "$p exists"; exit 3; }; done
g c2cells $C/2d-unfolding/re1/re1_c2_cells.py --readout $R/readout_2d_full.json --cov $COV --q $Q \
  --expect-readout-sha256 ac759b0347b2bdd741d57bcdd749ac0fc51decc323e702ef239ba34eb3a32084 \
  --expect-cov-sha256 6689d2fc2a795a72e66ee953a32d94c7906dd81a866771979f379c5f163a9ddc \
  --expect-q-sha256 8ccb4d723c3dbf737a7fb1d5236e5e25409c41b42b64ac55dccbbc12f595600e \
  --tsv $R/c2_d2_cells_regen.tsv --out $R/c2_cells.json > $R/c2_cells.log 2>&1
cmp $R/c2_d2_cells_regen.tsv $R/c2_d2_cells.tsv && echo "c2_d2_cells.tsv regenerated byte for byte"
T=$A/nd-unfolding/uq_5d/z_pilot_20260916_a5/z-cv.npz; C5D=$A/nd-unfolding/products/5d/xsec_5d_MEFHC_5iter_lgbm.root
g extras $C/nd-unfolding/re1/re1_report2_extras.py --cur3d $CUR3D --p3 $F/new/xsec_3d_p3.root --eu $EU \
  --c5 $O/5d/p5c.npz --cur5d $C5D --trunk $T --npz5d $NPZ5D \
  --expect-cur3d-sha256 $CUR3D_SHA --expect-p3-sha256 c16b622b4970800121b1d92dad91407878e0f4546375bfe27cdd3257d46d8c63 \
  --expect-eu-sha256 $EU_SHA --expect-c5-sha256 1fa60dfcb929fc4fe9b88cc64aa9c87f1ee971af751bde08ec69a7d6837462c7 \
  --expect-cur5d-sha256 630306e20e4e175bde8b459174842a58e4f4b5a694b8a5018e730a952820aec8 \
  --expect-trunk-sha256 3d7465f66fbe66b0dfcf09b6fc51249f227fb33e97ae40bc78dda90275e918c5 --expect-npz5d-sha256 $NPZ5D_SHA \
  --out $R/report2_extras.json > $R/report2_extras.log 2>&1
tail -1 $R/c2_cells.log; tail -1 $R/report2_extras.log

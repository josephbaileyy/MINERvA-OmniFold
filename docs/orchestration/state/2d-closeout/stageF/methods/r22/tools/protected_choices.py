"""Write the PROTECTED gaps as Joseph's choices (RULES.md §5: they go to Joseph, quoting the exact sentences).

usage: python3 -I protected_choices.py R22_DIR LANE.tsv INDEP.tsv OUT.md
Every gap that either classification calls PROTECTED is listed once, grouped by its first protection item (the lane's
item where the lane says PROTECTED, else the independent one's), with the rater's exact QUOTE (located in the rated
text by analyze.py's rule), the rater's CHANGE, the SHARE, and which classifications call it PROTECTED."""
import csv
import sys
from collections import defaultdict
from pathlib import Path

R = Path(sys.argv[1])
G = list(csv.DictReader(open(R / "gap" / "gaps.tsv"), delimiter="\t"))
A = {r["id"]: r for r in csv.DictReader(open(sys.argv[2]), delimiter="\t")}
B = {r["id"]: r for r in csv.DictReader(open(sys.argv[3]), delimiter="\t")}
ORDER = ["A1", "A4", "A5", "A7", "FROZEN", "B1", "B3", "C1", "C2", "C4", "C5", "C7", "C8", "C9", "C10", "C12", "C13",
         "C14", "C18", "C20", "C23", "B2"]
groups = defaultdict(list)
for g in G:
    a, b = A[g["id"]], B[g["id"]]
    pa, pb = a["class"] == "PROTECTED", b["class"] == "PROTECTED"
    if not (pa or pb):
        continue
    item = (a if pa else b)["item"]
    first = item.replace(" ", ",").split(",")[0]
    key = f"ledger row {first}" if first[:1] == "F" and first[1:2].isdigit() else next(
        (o for o in ORDER if first.startswith(o)), first)
    groups[key].append((g, a, b, "both" if pa and pb else ("lane only" if pa else "independent only")))
lines = ["# r22 Step 1: the PROTECTED gaps, as choices for Joseph", "",
         "Generated by `tools/protected_choices.py` from `gap/gaps.tsv`, `gap/class-lane.tsv` and `gap/class-indep.tsv`."
         " Each entry quotes the rater's QUOTE exactly as it prints in the rated text (blinded: the paper's rater copy,"
         " or the note piece). Nothing here has been reworded around: each is a choice, keep the text or allow the"
         " change.", ""]
n = 0
for key in sorted(groups, key=lambda k: (ORDER.index(k) if k in ORDER else len(ORDER), k)):
    rows = groups[key]
    lines += [f"## {key} ({len(rows)})", ""]
    for g, a, b, who in rows:
        n += 1
        doc = "paper" if g["input"] == "paper" else f"note {g['input']}"
        lines += [f"**{g['id']}** ({doc}, {g['model']}, SHARE {float(g['share']):g}; PROTECTED: {who})",
                  f"- Sentence: \"{g['quote']}\"",
                  f"- Rater's change: {g['change']}",
                  f"- Lane: {a['class']} [{a['item']}]: {a['reason']}",
                  f"- Independent: {b['class']} [{b['item']}]: {b['reason']}",
                  "<!-- absence-ok: quotes a sentence the rater quoted from the rated text, and the classifiers'"
                  " reasons; not a claim that a result is absent -->", ""]
lines.insert(4, f"{n} gaps in {len(groups)} groups.")
lines.insert(5, "")
Path(sys.argv[4]).write_text("\n".join(lines))
print(n, "gaps;", {k: len(v) for k, v in groups.items()})

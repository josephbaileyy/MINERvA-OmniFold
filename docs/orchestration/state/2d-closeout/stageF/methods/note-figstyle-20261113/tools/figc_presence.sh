hit=$(awk -F'|' '$2 ~ /^(ll5d_|rsn_|e96data|rdx_|t2a)/' "$T/q")
[ -z "$hit" ] || { echo "FENCE STOP:"; printf '%s\n' "$hit"; fin 11; }

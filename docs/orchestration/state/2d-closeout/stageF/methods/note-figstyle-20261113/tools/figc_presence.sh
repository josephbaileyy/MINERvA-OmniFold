# No set -u.
SELF=$1
fin() { rm -f -- "$SELF"; exit "$1"; }
[ -n "$SELF" ] && [ -f "$SELF" ] || exit 9
echo "figc presence host=$(hostname) utc=$(date -u +%FT%TZ) sha256=$(sha256sum "$SELF" | cut -d' ' -f1)"

#!/usr/bin/env python3
"""Generate b5d_read.sh (and the launcher) from the bound BSEL read connect (199cc946) and launcher template, with:
the source list = LL5D's committed manifest rows in groups `toys` and `null_roles` (1,654, each with its manifest pin)
plus the flux constraint at s1_assemble.CONSTRAINT_SHA256; the names bsel -> b5d. Deterministic: rerun gives the same
bytes. usage: gen_b5d_read.py (from the repo root)"""
import hashlib
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[6]
SEL = REPO / "docs/orchestration/state/ben-b-20261124/selection-20261124/connect"
HERE = Path(__file__).resolve().parent
MANIFEST = REPO / "docs/orchestration/state/measurement-paper/5d-community-20261024/fd/receipts-ll5d/hpss-u/hpss_ll5d_u_list.tsv"
MANIFEST_SHA = "980bb95e20eac386a220bb7d0dbb16a5a3477248688f9a72bc07671a7ad5842d"
BSEL_READ_SHA = "199cc946b5a7238873f99702b55caf0872fce95ed3e253cb9fdbc67c400ad547"
CONSTRAINT = ("e38ad7d28354d071577113a18c8c569f88b6239f7fb193d20285273f172fc0c2",
              "/pscratch/sd/j/josephrb/MINERvA-OmniFold/MINERvA101/opt/etc/MParamFiles/data/FluxConstraints/sorted_NuEConstraint_FHC_RHC_IMD.txt")
GROUPS = ("toys", "null_roles")


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def sources() -> list[tuple[str, str]]:
    assert sha(MANIFEST) == MANIFEST_SHA, "the LL5D manifest is not its pin"
    rows = [l.rstrip("\n").split("\t") for l in MANIFEST.read_text().splitlines() if l.strip()]
    out = [(s, p) for g, s, p in rows if g in GROUPS]
    assert len(out) == 1654 and len({Path(p).name for _, p in out}) == 1654, len(out)
    assert all(re.fullmatch(r"[0-9a-f]{64}", s) for s, _ in out)
    return out + [CONSTRAINT]


def main() -> None:
    read = SEL / "bsel_read.sh"
    assert sha(read) == BSEL_READ_SHA, "the BSEL read connect is not the bound one"
    s = read.read_text()
    head, rest = s.split("SOURCES='", 1)
    _, tail = rest.split("'\nNSRC=6\n", 1)
    src = sources()
    body = "\n".join(f"{h} {p}" for h, p in src)
    s = head + "SOURCES='" + body + "'\nNSRC=" + str(len(src)) + "\n" + tail
    rep = [("# (b) part 1 (and part 3's tables): the one read connect (B-SEL-DECLARATION.md §1).",
            "# (b) part 3: LL5D's toys, the products they were graded against, and the flux constraint (B5D-DECLARATION.md\n# §2). Generated by gen_b5d_read.py from the bound BSEL read connect (199cc946); only the sources and names differ."),
           ("#   usage: bsel_read.sh", "#   usage: b5d_read.sh"),
           ("OUT=/pscratch/sd/j/josephrb/bsel-20261124", "OUT=/pscratch/sd/j/josephrb/b5d-20261124"),
           ("FR=$OUT/fetch-bsel", "FR=$OUT/fetch-b5d"),
           ("connect-bsel", "connect-b5d"), ("bsel_read.sh", "b5d_read.sh"), ("bsel read rc=", "b5d read rc="),
           ('"fetch-bsel"', '"fetch-b5d"'), ("fetch-bsel.tar", "fetch-b5d.tar"), ("$OUT/fetch-bsel/", "$OUT/fetch-b5d/")]
    for a, b in rep:
        assert a in s, a
        s = s.replace(a, b)
    assert "bsel" not in s.lower().replace("the bound bsel read connect", ""), [l for l in s.splitlines() if "bsel" in l.lower()][:3]
    (HERE / "b5d_read.sh").write_text(s)
    lt = (SEL / "bsel_launch.template.sh").read_text()
    lrep = [("# (b) part 1's read launcher: S2R's reviewed launcher (f8cd325d) with one connect.",
             "# (b) part 3's read launcher: the bound BSEL launcher (a0fc824f) with b5d's names; generated by gen_b5d_read.py."),
            ("bsel_launch.sh", "b5d_launch.sh"), ('S="$HERE/bsel_read.sh"', 'S="$HERE/b5d_read.sh"'),
            ("/dev/shm/bselc.", "/dev/shm/b5dc."), ("bsel-20261124", "b5d-20261124"), ("fetch-bsel", "fetch-b5d"),
            ("connect-bsel", "connect-b5d")]
    for a, b in lrep:
        assert a in lt, a
        lt = lt.replace(a, b)
    (HERE / "b5d_launch.template.sh").write_text(lt)
    rs = sha(HERE / "b5d_read.sh")
    (HERE / "b5d_launch.sh").write_text(lt.replace("@@READ_SHA@@", rs))
    print("b5d_read.sh", rs, "sources", len(src))
    print("b5d_launch.sh", sha(HERE / "b5d_launch.sh"))


if __name__ == "__main__":
    main()

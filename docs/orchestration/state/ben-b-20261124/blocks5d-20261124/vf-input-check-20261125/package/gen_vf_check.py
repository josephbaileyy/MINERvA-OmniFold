#!/usr/bin/env python3
"""Generate vf_inputs_check.sh (the read-only input-existence check) and vf_inputs_launch.sh from inputs.tsv.

inputs.tsv: one line per input, tab-separated: phase, readout, role, path, pinned_sha256 (64 hex or NONE),
pinned_size (bytes or NONE), source (committed file:line of the pin). A path starting "hpss:" is an HPSS archive path,
checked with a read-only `hsi -q ls -l`. Rerunning gives the same bytes.

The check, on a Perlmutter login node, from stdin (no file written anywhere; output is stdout only):
  the window (now <= window end); the fence by sacct (no non-terminal job of this user whose name starts with a fenced
  prefix); then per input: exists or not; for a file, size, mtime and one O_NOATIME read (dd iflag=noatime) into
  sha256sum, compared with the pin, and the atime before and after (a failed read is READ-ERROR with dd's rc; a file over
  10 GiB, by its recorded or actual size, is stat only: EXISTS-UNHASHED, its size compared with the pin's); for a
  directory, its entry count; for an HPSS path,
  hsi ls. One TSV row per input. A file that would be read after the window end is reported NOT-CHECKED.
"""
import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main() -> int:
    rows = [l.rstrip("\n") for l in (HERE / "inputs.tsv").read_text().splitlines() if l.strip()]
    for r in rows:
        f = r.split("\t")
        assert len(f) == 7, r
        assert f[4] == "NONE" or (len(f[4]) == 64 and all(c in "0123456789abcdef" for c in f[4])), r
        assert "'" not in r, r
    body = "\n".join(rows)
    script = f"""#!/bin/bash
# V_F recompute: the read-only existence check of every Phase 1 and Phase 2 input (director's GO, 2026-11-25).
# Generated by gen_vf_check.py from inputs.tsv. Runs from stdin on a login node; writes nothing; prints TSV to stdout.
#   positional parameters: <window_end_epoch> <fence prefixes, comma-separated> (the launcher sets them, then evals).
# No here-strings or here-documents (bash 4.4 writes those to a temporary file); the input list is read through a pipe.
WEND=$1; FENCE=$2
set -o pipefail
[[ "$WEND" =~ ^[0-9]{{10}}$ ]] || {{ echo "BAIL window end '$WEND'"; exit 9; }}
[ "$(date +%s)" -le "$WEND" ] || {{ echo "BAIL the window has ended"; exit 9; }}
echo "node $(hostname) nproc=$(nproc) loadavg $(cut -d' ' -f1-3 /proc/loadavg)"; date -u +%Y-%m-%dT%H:%M:%SZ
echo "== fence (sacct)"
PRE=(${{FENCE//,/ }})
ACT=$(sacct -n -X -u "$USER" -S now-14days -s PENDING,RUNNING,REQUEUED,SUSPENDED,RESIZING -o JobID%20,JobName%60,State%14 2>&1) || {{ echo "BAIL sacct failed: $ACT"; exit 9; }}
for p in "${{PRE[@]}}"; do
  hit=$(printf '%s\\n' "$ACT" | awk -v p="$p" 'index($2,p)==1')
  [ -z "$hit" ] || {{ echo "BAIL fence: a non-terminal job starts with '$p': $hit"; exit 9; }}
done
echo "fence clear for: $FENCE"
printf 'phase\\treadout\\trole\\tpath\\tpinned_sha256\\tfound_sha256\\tsize\\tmtime\\tstatus\\tnote\\n'
INPUTS='{body}'
printf '%s\\n' "$INPUTS" | while IFS=$'\\t' read -r PH RO ROLE P PIN PSZ SRC; do
  [ -n "$P" ] || continue
  if [[ "$P" == hpss:* ]]; then
    hp=${{P#hpss:}}
    out=$(hsi -q ls -l "$hp" 2>&1 < /dev/null); r=$?
    if [ $r -eq 0 ] && ! printf '%s' "$out" | grep -qi 'no such\\|not found\\|HPSS_ENOENT'; then st=EXISTS; else st=MISSING; fi
    sz=$(printf '%s\\n' "$out" | awk 'NF>=5 && $5 ~ /^[0-9]+$/ {{print $5; exit}}')
    printf '%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\n' "$PH" "$RO" "$ROLE" "$P" "$PIN" "-" "${{sz:--}}" "-" "$st" "hsi ls rc=$r"
    continue
  fi
  if [ ! -e "$P" ]; then
    printf '%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\n' "$PH" "$RO" "$ROLE" "$P" "$PIN" "-" "-" "-" MISSING "-"
    continue
  fi
  if [ -d "$P" ]; then
    n=$(find "$P" -mindepth 1 -maxdepth 1 2>/dev/null < /dev/null | wc -l)
    mt=$(stat -c %Y "$P")
    printf '%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\n' "$PH" "$RO" "$ROLE" "$P" "$PIN" "-" "-" "$mt" EXISTS "directory, $n entries"
    continue
  fi
  st=($(stat -c '%s %Y %X' "$P")); sz=${{st[0]}}; mt=${{st[1]}}; a0=${{st[2]}}
  if [ "$(date +%s)" -gt "$WEND" ]; then
    printf '%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\n' "$PH" "$RO" "$ROLE" "$P" "$PIN" "-" "$sz" "$mt" NOT-CHECKED "window ended before its read"
    continue
  fi
  if {{ [ "$PSZ" != NONE ] && [ "$PSZ" -gt 10737418240 ]; }} || [ "$sz" -gt 10737418240 ]; then
    note="over 10 GiB: stat only"
    [ "$PSZ" != NONE ] && {{ [ "$sz" = "$PSZ" ] && note="$note; size equals the pinned $PSZ" || note="$note; size differs from the pinned $PSZ"; }}
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$PH" "$RO" "$ROLE" "$P" "$PIN" "-" "$sz" "$mt" EXISTS-UNHASHED "$note"
    continue
  fi
  h=$(dd if="$P" iflag=noatime bs=8M status=none | sha256sum | cut -d' ' -f1; exit ${{PIPESTATUS[0]}}); dr=$?
  a1=$(stat -c %X "$P")
  if [ "$dr" -ne 0 ] || [ "${{#h}}" -ne 64 ]; then
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$PH" "$RO" "$ROLE" "$P" "$PIN" "-" "$sz" "$mt" READ-ERROR "dd rc=$dr"
    continue
  fi
  if [ "$PIN" = NONE ]; then st=EXISTS; elif [ "$h" = "$PIN" ]; then st=EXISTS; else st=CHANGED; fi
  note="atime $([ "$a0" = "$a1" ] && echo unmoved || echo MOVED)"
  [ "$PIN" = NONE ] && note="$note; no pin"
  [ "$PSZ" != NONE ] && [ "$sz" != "$PSZ" ] && note="$note; size differs from the pinned $PSZ"
  printf '%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\t%s\\n' "$PH" "$RO" "$ROLE" "$P" "$PIN" "$h" "$sz" "$mt" "$st" "$note"
done
date -u +%Y-%m-%dT%H:%M:%SZ
echo "done rc=0"
"""
    (HERE / "vf_inputs_check.sh").write_text(script)
    sha = hashlib.sha256(script.encode()).hexdigest()
    launch = f"""#!/bin/bash
# The launcher for vf_inputs_check.sh. saul, then a loginNN (inner hop's host key checked strictly). The script goes on
# stdin into a shell variable on the node; its sha256 must equal the approved one, or the node exits 8 before anything
# runs; it runs by eval of that variable in a subshell (no exec, so no argument-size limit), so nothing is written. Output: stdout only, saved here.
# Usage: bash vf_inputs_launch.sh <new empty local dir> <loginNN> <window_end_epoch> <fence prefixes, comma-sep>
F=${{1:?session dir}}; NODE=${{2:?loginNN}}; WEND=${{3:?window end epoch}}; FENCE=${{4:?fence}}
HERE=$(cd "$(dirname "$0")" && pwd)
S="$HERE/vf_inputs_check.sh"; SHA={sha}
[ -d "$F" ] && [ -z "$(ls -A "$F")" ] || {{ echo "STOP: $F is not a new empty directory"; exit 9; }}
case "$NODE" in login[0-9][0-9]) ;; *) echo "STOP: '$NODE' is not a login node name"; exit 9;; esac
[[ "$WEND" =~ ^[0-9]{{10}}$ ]] || {{ echo "STOP: window end '$WEND'"; exit 9; }}
[ "$(date +%s)" -le "$WEND" ] || {{ echo "STOP: the window has ended"; exit 9; }}
[[ "$FENCE" =~ ^[A-Za-z0-9_.-]+(,[A-Za-z0-9_.-]+)*$ ]] || {{ echo "STOP: fence '$FENCE'"; exit 9; }}
[ "$(shasum -a 256 "$S" | cut -d' ' -f1)" = "$SHA" ] || {{ echo "STOP: the local check script is not the approved one"; exit 8; }}
SSH=(-o ControlPath=none -o BatchMode=yes -o ConnectTimeout=20 -o ServerAliveInterval=15 -o ServerAliveCountMax=8)
HOP=(-o BatchMode=yes -o ConnectTimeout=10 -o ServerAliveInterval=15 -o ServerAliveCountMax=8 -o StrictHostKeyChecking=yes -o UpdateHostKeys=no)
R="s=\\$(cat; echo x); s=\\${{s%x}}; h=\\$(printf '%s' \\"\\$s\\" | sha256sum | cut -d' ' -f1); if [ \\"\\$h\\" != {sha} ]; then echo \\"STOP: stdin script sha256 \\$h is not {sha}\\"; exit 8; fi; echo \\"node \\$(hostname) script sha256 \\$h\\"; ( set -- $WEND $FENCE; eval \\"\\$s\\" ) < /dev/null; r=\\$?; echo \\"script rc=\\$r\\"; exit \\$r"
ssh "${{SSH[@]}}" saul.nersc.gov "ssh ${{HOP[*]}} $NODE $(printf '%q' "$R")" < "$S" > "$F/session.out" 2> "$F/session.err"
rc=$?
echo "ssh rc=$rc"
grep -q '^script rc=' "$F/session.out" || {{ echo "STOP: the session did not report a script rc"; exit 9; }}
grep -q '^BAIL ' "$F/session.out" && {{ echo "STOP: the check bailed before reading anything"; grep '^BAIL ' "$F/session.out"; exit 9; }}
awk -F'\\t' 'NF==10' "$F/session.out" > "$F/vf_inputs_check.tsv"
echo "rows $(($(wc -l < "$F/vf_inputs_check.tsv") - 1))"
awk -F'\\t' 'NR>1 {{c[$1" "$9]++}} END {{for (k in c) print k, c[k]}}' "$F/vf_inputs_check.tsv" | sort
exit $rc
"""
    (HERE / "vf_inputs_launch.sh").write_text(launch)
    print("check", sha)
    print("launch", hashlib.sha256(launch.encode()).hexdigest())
    print("inputs", hashlib.sha256((HERE / "inputs.tsv").read_bytes()).hexdigest(), len(rows), "rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())

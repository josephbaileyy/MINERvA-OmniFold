#!/usr/bin/env python3
"""Generate the login-only probe of custody's two sacct reads, from custody's own code path.

usage: python3 -I -B gen_probe.py REPO
  REPO  a checkout whose nd-unfolding/fd_rpd_reco_custody.py is the custody module under test

It loads custody, stubs subprocess.run to capture the commands cov2d_fence() builds (with a fixed clock), and
writes custody_sacct_probe.sh beside this file. The probe runs exactly those two commands on a login node, each with
stderr merged into stdout, and prints each one's rc and output. It writes nothing. The one value it computes on the node
is the family read's -S, with the same arithmetic as cov2d_family_start (now minus COV2D_FAMILY_DAYS days, in the
node's local time, %Y-%m-%dT%H:%M:%S). Everything else is the captured argv, quoted byte for byte. The probe exits 0
only if both reads exit 0.
"""

from __future__ import annotations

import hashlib
import importlib.util
import shlex
import sys
from pathlib import Path
from types import SimpleNamespace

HERE = Path(__file__).resolve().parent
OUT = HERE / "custody_sacct_probe.sh"
CLOCK = 1795400000.0


def main() -> int:
    repo = Path(sys.argv[1])
    module_path = repo / "nd-unfolding" / "fd_rpd_reco_custody.py"
    module_sha = hashlib.sha256(module_path.read_bytes()).hexdigest()
    spec = importlib.util.spec_from_file_location("custody_probe_source", module_path)
    assert spec is not None and spec.loader is not None
    custody = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(custody)

    calls: list[list[str]] = []

    def run(command: list[str], **kwargs: object) -> SimpleNamespace:
        assert command[0] == "sacct", command
        assert kwargs.get("stderr") is custody.subprocess.STDOUT
        calls.append(list(command))
        named = "60909280|a|COMPLETED\n60911676|b|COMPLETED\n"
        return SimpleNamespace(returncode=0, stdout=named if "-j" in command else "", stderr=None)

    custody.subprocess.run = run
    custody.time.time = lambda: CLOCK
    assert custody.cov2d_fence()["status"] == "PASS"
    assert len(calls) == 2, calls
    named, family = calls
    assert "-j" in named and "-u" in family
    position = family.index("-S") + 1
    assert family[position] == custody.cov2d_family_start(CLOCK)
    days = custody.COV2D_FAMILY_DAYS
    assert isinstance(days, int) and 0 < days <= 14

    def line(argv: list[str], start_at: int | None = None) -> str:
        words = [shlex.quote(word) for word in argv]
        if start_at is not None:
            words[start_at] = '"$start"'
        return " ".join(words)

    named_line = line(named)
    family_line = line(family, position)
    text = f"""#!/bin/bash
# custody_sacct_probe.sh: login-only, read-only probe of custody's two COV2D-fence sacct reads (limitation-resolver,
# 2026-11-23, the director's real-sacct rule). Generated by gen_probe.py from fd_rpd_reco_custody.py
# sha256 {module_sha}. It runs each read once, with stderr merged, prints its rc and output, and writes nothing.
# No squeue, no job, nothing written on the cluster.
echo "== host $(hostname) utc $(date -u +%FT%TZ) local $(date +%FT%T%z)"
start=$(date -d "@$(( $(date +%s) - {days} * 86400 ))" +%Y-%m-%dT%H:%M:%S) || {{ echo "STOP: start date failed"; exit 3; }}
echo "== named: {named_line}"
out=$({named_line} 2>&1); nrc=$?
echo "named rc=$nrc"
printf '%s\\n' "$out" | sed 's/^/named: /'
echo "== family (start $start): {family_line.replace('"$start"', '$start')}"
out=$({family_line} 2>&1); frc=$?
echo "family rc=$frc"
printf '%s\\n' "$out" | sed 's/^/family: /'
echo "== end utc $(date -u +%FT%TZ)"
[ "$nrc" -eq 0 ] && [ "$frc" -eq 0 ]
"""
    OUT.write_text(text)
    print(hashlib.sha256(text.encode()).hexdigest(), OUT.name)
    print("custody", module_sha)
    print("named ", named_line)
    print("family", family_line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
